i18n_code = f'''"""
Velodictum - Localization and Internationalization (i18n) Engine
Provides zero-dependency, high-performance translation lookup with dynamic live switching.
"""
from typing import Dict, Any

_CURRENT_LANGUAGE = "en"

TRANSLATIONS: Dict[str, Dict[str, str]] = {{
    "en": {json.dumps(EN_TRANSLATIONS, indent=8, ensure_ascii=False)},
    "de": {json.dumps(DE_TRANSLATIONS, indent=8, ensure_ascii=False)},
}}


def set_current_language(lang: str) -> None:
    global _CURRENT_LANGUAGE
    if lang in ("en", "de"):
        _CURRENT_LANGUAGE = lang


def get_current_language() -> str:
    return _CURRENT_LANGUAGE


def tr(_key: str, **kwargs: Any) -> str:
    lang_dict = TRANSLATIONS.get(_CURRENT_LANGUAGE, TRANSLATIONS.get("en", {{}}))
    text = lang_dict.get(_key)
    if text is None:
        text = TRANSLATIONS.get("en", {{}}).get(_key, _key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
'''

